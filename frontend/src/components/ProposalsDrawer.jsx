import { useCallback, useEffect, useState } from 'react';
import { ArrowRight, Bot, Check, GitBranch, ListPlus, Lock, RefreshCw, X } from 'lucide-react';
import api, { errorMessage } from '../api/client.js';
import { CATEGORY_LABEL, PriorityBadge, StatusBadge } from './badges.jsx';

const STATE_CLS = {
  PENDING: 'bg-amber-100 text-amber-800',
  APPROVED: 'bg-emerald-100 text-emerald-700',
  REJECTED: 'bg-gray-200 text-gray-700',
};

function ActionRow({ action, proposal }) {
  const creates = proposal.proposedActions.filter((a) => a.type === 'CREATE_TASK');
  const nameOf = (ref) => creates.find((c) => c.tempId === ref)?.title || proposal.refTasks[ref]?.title || 'Unknown task';

  if (action.type === 'CREATE_TASK') {
    return (
      <li className="rounded-lg border border-cream-200 bg-white p-3">
        <div className="flex items-start justify-between gap-2">
          <p className="flex items-center gap-2 text-sm font-semibold">
            <ListPlus size={14} className="text-brand-600" /> {action.title}
          </p>
          <PriorityBadge priority={action.priority} />
        </div>
        <p className="mt-1 text-xs text-ink-700">New task · {CATEGORY_LABEL[action.category]}</p>
        {action.dependsOnRefs.length > 0 && (
          <p className="mt-2 flex flex-wrap items-center gap-1 text-xs text-ink-700">
            <GitBranch size={12} /> After:
            {action.dependsOnRefs.map((r) => (
              <span key={r} className="rounded bg-cream-100 px-1.5 py-0.5">{nameOf(r)}</span>
            ))}
          </p>
        )}
        {action.rationale && <p className="mt-1 text-xs italic text-ink-700/70">{action.rationale}</p>}
      </li>
    );
  }

  if (action.type === 'UPDATE_TASK_STATUS') {
    const current = proposal.refTasks[action.taskId];
    return (
      <li className="rounded-lg border border-cream-200 bg-white p-3">
        <p className="text-sm font-semibold">{current?.title || 'Unknown task'}</p>
        <p className="mt-1 flex items-center gap-2 text-xs">
          {current && <StatusBadge status={current.status} />}
          <ArrowRight size={12} />
          <StatusBadge status={action.newStatus} />
        </p>
        {action.blockerNote && <p className="mt-1 text-xs text-red-700">Blocker: {action.blockerNote}</p>}
        {action.rationale && <p className="mt-1 text-xs italic text-ink-700/70">{action.rationale}</p>}
      </li>
    );
  }

  return (
    <li className="rounded-lg border border-cream-200 bg-white p-3 text-sm">
      <span className="font-semibold">{nameOf(action.taskRef)}</span> <GitBranch size={12} className="inline" /> depends on{' '}
      <span className="font-semibold">{nameOf(action.dependsOnRef)}</span>
      {action.rationale && <p className="mt-1 text-xs italic text-ink-700/70">{action.rationale}</p>}
    </li>
  );
}

function ProposalCard({ proposal, canReview, onDecision }) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const counts = proposal.proposedActions.reduce((acc, a) => ({ ...acc, [a.type]: (acc[a.type] || 0) + 1 }), {});

  async function decide(kind) {
    setBusy(true);
    setError('');
    try {
      await api.post(`/proposals/${proposal.id}/${kind}`, kind === 'reject' ? {} : undefined);
      onDecision();
    } catch (err) {
      setError(errorMessage(err));
      setBusy(false);
    }
  }

  return (
    <article className="card p-4">
      <div className="flex items-start justify-between gap-2">
        <div>
          <p className="flex items-center gap-2 text-sm font-semibold">
            <Bot size={16} className="text-brand-600" /> {proposal.triggerType === 'BRIEF' ? 'Launch brief' : 'Meeting transcript'} proposal
          </p>
          <p className="mt-1 text-xs text-ink-700">{proposal.summary}</p>
        </div>
        <span className={`shrink-0 rounded-full px-2 py-0.5 text-xs font-semibold ${STATE_CLS[proposal.status]}`}>{proposal.status}</span>
      </div>

      <div className="mt-2 flex flex-wrap gap-1.5 text-xs">
        {proposal.source === 'FALLBACK' && (
          <span className="rounded bg-cream-200 px-1.5 py-0.5" title="Gemini was unavailable, so the built-in parser generated this">
            Generated by fallback parser
          </span>
        )}
        {counts.CREATE_TASK && <span className="rounded bg-brand-50 px-1.5 py-0.5 text-brand-700">{counts.CREATE_TASK} new task(s)</span>}
        {counts.UPDATE_TASK_STATUS && <span className="rounded bg-brand-50 px-1.5 py-0.5 text-brand-700">{counts.UPDATE_TASK_STATUS} status update(s)</span>}
        {counts.ADD_DEPENDENCY && <span className="rounded bg-brand-50 px-1.5 py-0.5 text-brand-700">{counts.ADD_DEPENDENCY} link(s)</span>}
      </div>

      {proposal.warnings.length > 0 && (
        <ul className="mt-2 space-y-1 rounded-lg bg-amber-50 p-2 text-xs text-amber-800">
          {proposal.warnings.map((w, i) => <li key={i}>• {w}</li>)}
        </ul>
      )}

      <ul className="mt-3 space-y-2">
        {proposal.proposedActions.map((a, i) => <ActionRow key={i} action={a} proposal={proposal} />)}
      </ul>

      {proposal.status === 'REJECTED' && proposal.rejectionReason && (
        <p className="mt-2 text-xs text-ink-700">Reason: {proposal.rejectionReason}</p>
      )}
      {error && <p className="mt-3 rounded-lg bg-red-50 px-3 py-2 text-sm text-red-700">{error}</p>}

      {proposal.status === 'PENDING' && (
        <div className="mt-4">
          {canReview ? (
            <div className="flex gap-2">
              <button disabled={busy} onClick={() => decide('approve')} className="btn-primary flex-1">
                <Check size={16} /> {busy ? 'Working…' : 'Approve & Execute'}
              </button>
              <button disabled={busy} onClick={() => decide('reject')} className="btn-ghost">
                <X size={16} /> Reject
              </button>
            </div>
          ) : (
            <p className="flex items-center gap-2 rounded-lg bg-cream-100 px-3 py-2 text-xs text-ink-700">
              <Lock size={14} /> Only a Lead or Admin can approve or reject AI proposals.
            </p>
          )}
        </div>
      )}
    </article>
  );
}

export default function ProposalsDrawer({ projectId, canReview, focusId, onClose, onChanged }) {
  const [tab, setTab] = useState('PENDING');
  const [proposals, setProposals] = useState(null);
  const [error, setError] = useState('');

  const load = useCallback(async () => {
    try {
      const { data } = await api.get(`/projects/${projectId}/proposals`);
      setProposals(data.proposals);
    } catch (e) {
      setError(errorMessage(e));
    }
  }, [projectId]);

  useEffect(() => {
    load();
  }, [load]);

  const pending = (proposals || []).filter((p) => p.status === 'PENDING');
  const history = (proposals || []).filter((p) => p.status !== 'PENDING');
  const shown = (tab === 'PENDING' ? pending : history).sort((a, b) => (a.id === focusId ? -1 : b.id === focusId ? 1 : 0));

  return (
    <div className="fixed inset-0 z-40 flex justify-end bg-ink-900/40">
      <div className="flex h-full w-full max-w-xl flex-col bg-cream-50 shadow-xl">
        <header className="flex items-center justify-between border-b border-cream-200 px-5 py-4">
          <h2 className="flex items-center gap-2 font-semibold">
            <Bot size={18} className="text-brand-600" /> AI proposals
          </h2>
          <div className="flex items-center gap-3">
            <button onClick={load} aria-label="Refresh" className="text-ink-700 hover:text-ink-900"><RefreshCw size={16} /></button>
            <button onClick={onClose} aria-label="Close" className="text-ink-700 hover:text-ink-900"><X size={18} /></button>
          </div>
        </header>

        <div className="flex gap-1 border-b border-cream-200 px-5 pt-3">
          {[['PENDING', `Pending (${pending.length})`], ['HISTORY', `History (${history.length})`]].map(([key, label]) => (
            <button
              key={key}
              onClick={() => setTab(key)}
              className={`rounded-t-md px-3 py-1.5 text-sm ${tab === key ? 'bg-white font-semibold shadow-sm' : 'text-ink-700'}`}
            >
              {label}
            </button>
          ))}
        </div>

        <div className="flex-1 space-y-4 overflow-y-auto p-5">
          {error && <p className="rounded-lg bg-red-50 px-3 py-2 text-sm text-red-700">{error}</p>}
          {!proposals ? (
            <div className="animate-pulse space-y-3"><div className="h-32 rounded bg-cream-200" /><div className="h-32 rounded bg-cream-200" /></div>
          ) : shown.length === 0 ? (
            <p className="py-10 text-center text-sm text-ink-700/70">
              {tab === 'PENDING' ? 'No pending proposals. Add context to generate one.' : 'No reviewed proposals yet.'}
            </p>
          ) : (
            shown.map((p) => (
              <ProposalCard
                key={p.id}
                proposal={p}
                canReview={canReview}
                onDecision={() => {
                  load();
                  onChanged();
                }}
              />
            ))
          )}
        </div>
      </div>
    </div>
  );
}
